    let currentLang = 'en';

    function setLang(lang) {
        currentLang = lang;
        const html = document.documentElement;
        const body = document.body;
        const isAr = lang === 'ar';

        // Update HTML attributes
        html.lang = isAr ? 'ar' : 'en';
        html.dir = isAr ? 'rtl' : 'ltr';

        // Update active states on lang switchers
        document.querySelectorAll('#lang-en, #mobile-lang-en').forEach(el => el.classList.toggle('active', !isAr));
        document.querySelectorAll('#lang-ar, #mobile-lang-ar').forEach(el => el.classList.toggle('active', isAr));

        // Apply translations
        const t = translations[lang];
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (t[key] !== undefined) {
                if (key === 'footer_legal_line' || key === 'footer_copyright') {
                    el.innerHTML = t[key];
                } else {
                    el.textContent = t[key];
                }
            }
        });

        // Update placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (t[key] !== undefined) {
                el.placeholder = t[key];
            }
        });

        // Update page title
        document.title = t.page_title;

        // Update meta description
        const metaDesc = document.querySelector('meta[name="description"]');
        if (metaDesc) {
            metaDesc.content = isAr
                ? "مؤسسة نشر الحب تقدم الإغاثة الإنسانية الطارئة للعائلات المتضررة من النزاعات. 100% شفافية. كل تبرع ينقذ حياة."
                : "Spread Love Foundation provides emergency humanitarian relief to families affected by conflict. 100% transparent. Every donation saves lives.";
        }

        // Update hash without triggering scroll
        if (isAr) {
            if (window.location.hash !== '#ar') {
                history.replaceState(null, null, '#ar');
            }
        } else {
            if (window.location.hash === '#ar') {
                history.replaceState(null, null, ' ');
            }
        }

        // Restart toasts with new language data
        restartToasts();

        // Refresh testimonial carousel with new language data
        if (typeof restartTestimonials === 'function') restartTestimonials();
    }

